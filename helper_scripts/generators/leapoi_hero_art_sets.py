"""Writes the LEAPOI hero art sets config: every vanilla hero the tower can free, with the vanilla art sets its model comes from.

A hero of another culture created for the player takes a model from the player's culture, so the tower puts one of these on it instead.
Run from `helper_scripts/` as `python -m generators.leapoi_hero_art_sets` after a game patch adds heroes.
"""

import logging
import os
import re
import time
from typing import Dict, List, Set

from core.utilities import extract_tsv_data, load_tsv_data, log_elapsed_time, setup_script_logging
from generators.process_main_units_tables import LEAPOI_SOURCE_ROOT, find_source_factions_data_path

FACTIONS_DATA = f"{LEAPOI_SOURCE_ROOT}/{find_source_factions_data_path()}"
OUTPUT = f"{os.path.dirname(FACTIONS_DATA)}/hero_art_sets.lua"

# A vanilla hero row in factions_data.lua: its agent subtype, from a row with origin="vanilla" whose agent type is not a lord's.
HERO_ROW = re.compile(r'agent_subtype="([^"]+)", agent_type="(?!general"|colonel")[^"]+", origin="vanilla"')


def vanilla_hero_subtypes(factions_data_text: str) -> Set[str]:
    """Collects the agent subtypes of every vanilla hero row in factions_data.lua.

    Args:
        factions_data_text (str): The text of factions_data.lua.

    Returns:
        The agent subtypes.
    """
    return set(HERO_ROW.findall(factions_data_text))


def art_sets_by_subtype(rows: List[Dict[str, str]], subtypes: Set[str]) -> Dict[str, List[str]]:
    """Maps each subtype to its art sets. Art sets open to every culture are kept, and a subtype with none falls back to all of its own.

    Args:
        rows (List[Dict[str, str]]): The campaign_character_art_sets rows.
        subtypes (Set[str]): The agent subtypes to look up.

    Returns:
        Subtype -> sorted art set ids, for the subtypes that have any.
    """
    shared: Dict[str, List[str]] = {}
    every: Dict[str, List[str]] = {}
    for row in rows:
        subtype = row["agent_subtype"]
        if subtype not in subtypes:
            continue
        every.setdefault(subtype, []).append(row["art_set_id"])
        if not row["culture"] and not row["subculture"] and not row["faction"]:
            shared.setdefault(subtype, []).append(row["art_set_id"])
    return {subtype: sorted(shared.get(subtype) or every[subtype]) for subtype in sorted(every)}


def to_lua(art_sets: Dict[str, List[str]]) -> str:
    """Writes the art set map as a Lua module.

    Args:
        art_sets (Dict[str, List[str]]): Subtype -> art set ids.

    Returns:
        The Lua source.
    """
    lines = [
        "--- Generated by helper_scripts/generators/leapoi_hero_art_sets.py. Vanilla hero agent subtype -> the vanilla art sets its model comes from.",
        "--- A freed hero of another culture is given one, since the game would otherwise dress it in a model of the player's culture.",
        "return {",
    ]
    for subtype, ids in art_sets.items():
        lines.append(f'    ["{subtype}"] = {{ ' + ", ".join(f'"{art_set}"' for art_set in ids) + " },")
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    setup_script_logging()
    start_time = time.time()
    with open(FACTIONS_DATA, encoding="utf-8") as f:
        subtypes = vanilla_hero_subtypes(f.read())
    table = "campaign_character_art_sets_tables"
    rows, _, _ = load_tsv_data(f"{extract_tsv_data(table)}/db/{table}/data__.tsv")
    art_sets = art_sets_by_subtype(rows, subtypes)
    missing = sorted(subtypes - set(art_sets))
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(to_lua(art_sets))
    logging.info(f"Wrote {len(art_sets)} hero subtypes to {OUTPUT}. {len(missing)} have no art set: {', '.join(missing)}")
    log_elapsed_time("writing the hero art sets", start_time)
