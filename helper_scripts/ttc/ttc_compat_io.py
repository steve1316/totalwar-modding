"""Read and write Yet Another Tabletop Caps compat files (`script/ttc/*.lua`)."""

import glob
import os
import re
from dataclasses import dataclass
from typing import Dict, List, Optional, Set, Tuple

HAND_DIR = "../warhammer3_mods/!!!!!!!yet_another_tabletopcaps_compat/script/ttc"
ENTRY_PATTERN = re.compile(r'\{\s*"([^"]+)"\s*,\s*"(core|special|rare)"\s*(?:,\s*(\d+))?\s*\}')
FOOTER = """local ttc = core:get_static_object("tabletopcaps")
if ttc then
    ttc.add_setup_callback(function()
        ttc.add_unit_list(caps, true)
    end)
end
"""


@dataclass
class TtcEntry:
    """One `{key, category, weight}` entry from a compat file."""

    # Unit key from `main_units_tables`.
    key: str
    # `core`, `special` or `rare`.
    category: str
    # Point weight, or None when the entry has none (only `core`).
    weight: Optional[int]
    # 1-based line number in the file.
    line_no: int


def parse_ttc_text(text: str) -> List[TtcEntry]:
    """Parse every cap entry in a compat file's text.

    Args:
        text (str): File contents.

    Returns:
        The entries in file order.
    """
    entries = []
    for line_no, line in enumerate(text.splitlines(), start=1):
        for match in ENTRY_PATTERN.finditer(line):
            weight = int(match.group(3)) if match.group(3) else None
            entries.append(TtcEntry(match.group(1), match.group(2), weight, line_no))
    return entries


def parse_ttc_file(path: str) -> List[TtcEntry]:
    """Parse every cap entry in a compat file.

    Args:
        path (str): Path to the `.lua` file.

    Returns:
        The entries in file order.
    """
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        return parse_ttc_text(f.read())


def hand_files() -> List[str]:
    """List the hand-written compat files, excluding generated `_auto.lua` files.

    Returns:
        Paths sorted by filename.
    """
    paths = glob.glob(os.path.join(HAND_DIR, "!!!!!!!*.lua"))
    return sorted((p for p in paths if not p.endswith("_auto.lua")), key=lambda p: os.path.basename(p).lower())


def auto_file_path(package_name: str) -> str:
    """Return the generated compat file path for a mod.

    Args:
        package_name (str): The mod's `.pack` filename.

    Returns:
        Path of `!!!!!!!<name>_auto.lua` inside `HAND_DIR`.
    """
    name = package_name.lstrip("!").removesuffix(".pack")
    return os.path.join(HAND_DIR, f"!!!!!!!{name}_auto.lua")


def _format_entry(key: str, category: str, weight: Optional[int]) -> str:
    """Format one entry line the way the hand files do. `core` entries never get a weight, since TTC treats a missing weight as 1.

    Args:
        key (str): Unit key.
        category (str): `core`, `special` or `rare`.
        weight (Optional[int]): Point weight, or None for a weightless entry.

    Returns:
        The indented Lua line without a newline.
    """
    return f'    {{"{key}", "{category}"}},' if weight is None or category == "core" else f'    {{"{key}", "{category}", {weight}}},'


def render_caps_file(header: str, groups: Dict[str, List[Tuple[str, str, Optional[int]]]]) -> str:
    """Render a compat file, with groups and keys sorted so the output is deterministic.

    Args:
        header (str): Text of the header comment.
        groups (Dict[str, List[Tuple[str, str, Optional[int]]]]): Group comment to `(key, category, weight)` entries.

    Returns:
        The full file text.
    """
    lines = [f"-- {header}", "local caps = {"]
    for group in sorted(groups):
        lines.append(f"    -- {group}")
        lines.extend(_format_entry(*entry) for entry in sorted(groups[group], key=lambda e: e[0]))
    lines.append("}")
    lines.append("")
    return "\n".join(lines) + "\n" + FOOTER


def render_auto_file(mod_label: str, groups: Dict[str, List[Tuple[str, str, Optional[int]]]]) -> str:
    """Render a generated compat file.

    Args:
        mod_label (str): Mod name for the header comment.
        groups (Dict[str, List[Tuple[str, str, Optional[int]]]]): Group comment to `(key, category, weight)` entries.

    Returns:
        The full file text.
    """
    return render_caps_file(f"{mod_label} (auto-generated by update_ttc_compat.py, do not edit)", groups)


def hand_file_path(package_name: str) -> str:
    """Return the hand-written compat file path for a mod, which is the auto file's name without `_auto`.

    Args:
        package_name (str): The mod's `.pack` filename.

    Returns:
        Path of `!!!!!!!<name>.lua` inside `HAND_DIR`.
    """
    return auto_file_path(package_name).removesuffix("_auto.lua") + ".lua"


def add_entries(path: str, header: str, groups: Dict[str, List[Tuple[str, str, Optional[int]]]]) -> None:
    """Add entries to a hand file, each under its group comment, leaving the rest of the file untouched.

    A key the file already has gets its line replaced. A missing group comment is added before the closing `}` of `caps`, and an entry line
    without a trailing comma gets one so the new lines stay valid Lua. A missing file is created.

    Args:
        path (str): Hand file to edit or create.
        header (str): Header comment for a new file.
        groups (Dict[str, List[Tuple[str, str, Optional[int]]]]): Group comment to `(key, category, weight)` entries.

    Raises:
        ValueError: The file has no `local caps` table closed by a `}` line.
    """
    if not os.path.exists(path):
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(render_caps_file(header, groups))
        return
    with open(path, "rb") as f:
        text = f.read().decode("utf-8")
    newline = "\r\n" if "\r\n" in text else "\n"
    lines = text.splitlines()
    start = next((i for i, line in enumerate(lines) if line.strip().startswith("local caps")), None)
    close = next((i for i in range(start + 1, len(lines)) if lines[i].strip() == "}"), None) if start is not None else None
    if close is None:
        raise ValueError(f"{os.path.basename(path)} has no caps table to add entries to.")

    for group, entries in groups.items():
        for key, category, weight in entries:
            line = _format_entry(key, category, weight)
            existing = next((i for i in range(start, close) if (match := ENTRY_PATTERN.search(lines[i])) and match.group(1) == key), None)
            if existing is not None:
                lines[existing] = line
                continue
            heading = next((i for i in range(start, close) if lines[i].strip() == f"-- {group}"), None)
            if heading is None:
                lines[close:close] = [f"    -- {group}", line]
                close += 2
                continue
            # Insert after the group's last line, before the next group comment or the closing brace.
            end = next((i for i in range(heading + 1, close) if lines[i].strip().startswith("--")), close)
            while end > heading + 1 and not lines[end - 1].strip():
                end -= 1
            lines.insert(end, line)
            close += 1

    for i in range(start, close):
        match = ENTRY_PATTERN.search(lines[i])
        if match and not lines[i][match.end():].lstrip().startswith(","):
            lines[i] = lines[i][: match.end()] + "," + lines[i][match.end():]
    ending = newline if text.endswith(("\n", "\r")) else ""
    with open(path, "wb") as f:
        f.write((newline.join(lines) + ending).encode("utf-8"))


def set_header(path: str, header: str) -> bool:
    """Make a compat file's first line the `-- <header>` comment, replacing an existing first-line comment.

    Args:
        path (str): Compat file to edit.
        header (str): Header text, usually the mod's display name.

    Returns:
        True when the file changed.
    """
    with open(path, "rb") as f:
        text = f.read().decode("utf-8")
    newline = "\r\n" if "\r\n" in text else "\n"
    first, _, rest = text.partition("\n")
    updated = f"-- {header}{newline}" + (rest if first.startswith("--") else text)
    if updated == text:
        return False
    with open(path, "wb") as f:
        f.write(updated.encode("utf-8"))
    return True


def remove_lines(path: str, keys: Set[str]) -> List[str]:
    """Delete the lines holding entries for the given keys, leaving every other byte untouched.

    Args:
        path (str): Compat file to edit.
        keys (Set[str]): Unit keys whose entry lines should be removed.

    Returns:
        The removed lines, without line endings.
    """
    with open(path, "rb") as f:
        raw_lines = f.read().decode("utf-8").splitlines(keepends=True)
    kept, removed = [], []
    for line in raw_lines:
        match = ENTRY_PATTERN.search(line)
        if match and match.group(1) in keys:
            removed.append(line.rstrip("\r\n"))
        else:
            kept.append(line)
    if removed:
        with open(path, "wb") as f:
            f.write("".join(kept).encode("utf-8"))
    return removed
